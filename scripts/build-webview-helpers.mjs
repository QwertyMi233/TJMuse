import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const outputPath=path.join(root,'src/core/webview-helpers.generated.ts');
export function generateWebViewHelpers(){
  const helpers=[
    ['ZHIXUEMENG_DESCRIPTION_SCRIPT','zhixuemeng-description.ts','cleanZhixuemengDescription'],
    ['EXPIRED_PLATFORM_SESSION_SCRIPT','platform-session-errors.ts','isExpiredPlatformSession'],
  ];
  return '// Generated by scripts/build-webview-helpers.mjs. Do not edit.\n'+
    '// Store source as literals: Hermes does not preserve Function.toString() source.\n'+
    helpers.map(([constant,file,name])=>{
      const source=ts.createSourceFile(file,fs.readFileSync(path.join(root,'src/core',file),'utf8'),ts.ScriptTarget.Latest,true);
      const declaration=source.statements.find(s=>ts.isFunctionDeclaration(s)&&s.name?.text===name);
      if(!declaration)throw Error('Missing WebView helper: '+name);
      const plain=declaration.getText(source).replace(/^export\s+/,'');
      const js=ts.transpileModule(plain,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.None}}).outputText.trim();
      return 'export const '+constant+'='+JSON.stringify('(()=>{\n'+js+'\nreturn '+name+';\n})()')+';\n';
    }).join('');
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const generated=generateWebViewHelpers();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(outputPath,'utf8')!==generated)throw Error('Run node scripts/build-webview-helpers.mjs');
  }else fs.writeFileSync(outputPath,generated);
}
